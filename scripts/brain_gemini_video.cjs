// Spoken lines for a Gemini (Omni / Veo) video pair, written THROUGH the Sudegy brain (AGENTS.md rule 3).
// The visual part of each prompt is a fixed director template (docs/gemini-video-prompts-2026-11-19.md); only the
// words people hear come from the brain. Output: JSON { vertical, hook, lineA, lineB, prompts: { a, b } }.
// Usage: node scripts/brain_gemini_video.cjs <vertical> <out.json>
const fs = require('fs');
const SALES = 'C:/Users/Admin/sudegy-sales';
const brain = require(`${SALES}/sudegy_brain.js`);
const { askJSON } = require(`${SALES}/gemini.js`);
const [vertical = 'dental', out] = process.argv.slice(2);
if (!out) { console.error('usage: node scripts/brain_gemini_video.cjs <vertical> <out.json>'); process.exit(2); }
const offer = brain.OFFERS[vertical]; if (!offer) throw new Error('unknown vertical ' + vertical);

const TASK = `Two 8-second vertical video clips will be generated by an AI video model and joined with a match cut (same camera, same framing). A person speaks ONE short line to camera in each clip.
Clip A = the pain: evening, the clinic is closing, the desk phone keeps ringing and the receptionist cannot answer, so patients who want to book go elsewhere. Clip B = after Sudegy: same person, same place, calm, a booking request arrives on her phone by itself (patients can book from the clinic page at any hour).
The lines must match what is seen. lineB describes what the system lets patients do, not a promised outcome: never "مؤكدة", "مضمونة", "دائما", "كل", or any claim of more bookings.
The offer for this vertical: ${offer}

Return JSON exactly: {"hook":"...","lineA":"...","lineB":"..."}
RULES:
- Arabic, simple Saudi-friendly wording that is clear when spoken. Each line is ONE sentence.
- lineA starts with the hook. hook = the first 3 to 6 words of lineA, naming the pain in its first words.
- lineA: 7 to 12 words. lineB: 7 to 12 words, the result in plain words.
- No numbers, prices, percentages, guarantees, result claims presented as facts, emojis, links, exclamation marks, brand names other than سوديجي (lineB may mention سوديجي once).
- No medical claims, never "تشخيص".`;

(async () => {
  const system = brain.GULF_BRAIN();
  let r, problems = [];
  for (let attempt = 1; attempt <= 4; attempt++) {
    r = await askJSON(TASK + (problems.length ? `\nPREVIOUS ATTEMPT FAILED: ${problems.join('; ')}. Fix exactly that.` : ''), { system, temperature: 0.6 });
    problems = [];
    const wc = (s) => String(s || '').trim().split(/\s+/).filter(Boolean).length;
    if (!r.hook || wc(r.hook) < 3 || wc(r.hook) > 6) problems.push('hook must be 3-6 words');
    if (!String(r.lineA || '').startsWith(String(r.hook || '').replace(/[.؟?]$/, ''))) problems.push('lineA must start with the hook');
    for (const k of ['lineA', 'lineB']) { const n = wc(r[k]); if (n < 7 || n > 12) problems.push(`${k} has ${n} words (7-12)`); }
    const all = `${r.lineA} ${r.lineB}`;
    if (/[0-9٠-٩%!]/.test(all)) problems.push('no digits, % or !');
    if (/تشخيص|مضمون|نضمن|مؤكد|دائم/.test(all)) problems.push('banned word (guarantee or diagnosis)');
    if (!problems.length) break;
    console.error(`attempt ${attempt}: ${problems.join('; ')}`);
  }
  if (problems.length) throw new Error('brain lines failed the gate: ' + problems.join('; '));

  // visual template (learned rules: single continuous shot, locked camera for the match cut, 9:16, speech in quotes,
  // name the audio and exclude music, nothing on screen we would need to correct, space above the head for effects)
  const person = 'a Saudi woman in her early thirties, receptionist of a modern dental clinic, navy hijab, light grey scrubs, natural makeup';
  const frame = 'Vertical 9:16. One single continuous shot, no scene cuts. Locked-off camera on a tripod at eye level, medium close-up, her face centred in the upper third with clear space above her head, the reception desk with a phone and a laptop in front of her. Realistic, natural skin texture, shot on a modern smartphone camera.';
  const neg = 'No on-screen text, no captions, no logos, no subtitles, no music. Only her voice and room tone.';
  const prompts = {
    a: `${frame} ${person}. Evening, the clinic is closing, warm dim light, the desk phone keeps ringing and she cannot answer, she looks tired and stressed, rubs her forehead, then looks into the camera and says in Arabic: "${r.lineA}" Sound: phone ringing in the background, quiet clinic. ${neg}`,
    b: `${frame} The same woman at the same desk, exactly the same framing and camera position. Evening, the same warm light, now calm and smiling, her phone lights up with a new booking notification, she glances at it, relaxes, then looks into the camera and says in Arabic: "${r.lineB}" Sound: a soft notification chime, quiet clinic. ${neg}`,
  };
  const res = { vertical, hook: r.hook, lineA: r.lineA, lineB: r.lineB, prompts, made: new Date().toISOString() };
  fs.writeFileSync(out, JSON.stringify(res, null, 2));
  console.log(JSON.stringify(res, null, 2));
})().catch((e) => { console.error(e.message); process.exit(1); });
